export const TOTAL_DIRECT_BOOKINGS = ALL_BOOKINGS.length;

// Deterministic-ish shuffle (Fisher–Yates) so each page load gets a fresh order
// without needing a server-side random seed.
function shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
}

// How many items to pull into the rotating feed per page load.
const FEED_SIZE = 40;

export async function getRecentBookings() {
    const sample = shuffle(ALL_BOOKINGS).slice(0, FEED_SIZE);
    // minutesAgo is synthetic pacing for the rotation UI only (source has no timestamps) —
    // spread across a plausible "last hour or so" window, sorted ascending (most recent first).
    return sample
        .map((b) => ({
            property: b.property,
            roomType: b.roomType,
            country: b.country,
            minutesAgo: 1 + Math.floor(Math.random() * 58),
        }))
        .sort((a, b) => a.minutesAgo - b.minutesAgo);
}

